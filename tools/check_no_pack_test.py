class TheEnglishWordIsNotTheNeedle(unittest.TestCase):
    """`package` is Go's keyword, and the boundary this gate lives or dies on.

    820 `package` and 103 `packages` in the files this gate reads, on
    2026-09-06. Every single .go file opens with one. A needle that matched them could only be
    greened by exempting every Go file in the repository, which is not a gate.

    The carve-out is STRUCTURAL and case-aware, not a word list: `pack`
    followed by `age` in the SAME case run. `packAgent` and `PackAge` are
    camel-case boundaries and stay hits — the lookahead is why.
    """

    def test_the_go_package_clause_is_not_a_hit(self):
        root = tree(**{"internal/mapdef/load.go": "package mapdef\n\nvar x = 1\n"})
        try:
            code, out, err = run(root)
            self.assertEqual(code, 0, err)
            self.assertIn("clean", out)
        finally:
            shutil.rmtree(root)

    def test_every_spelling_of_the_english_word_is_not_a_hit(self):
        """AND THIS ASSERTION HAS A CONSEQUENCE, stated so nobody reads it as
        coverage it is not.

        The carve-out is a SUBSTRING rule, so the very thing that clears
        `packagePath` and `Subpackage` below clears `ArtPackage`,
        `LoadPackage`, `handlePackageFile`, `PackageTile`, `packageFS`,
        `ErrPackageNotLoaded` and a `"package"` JSON key — the most idiomatic
        rename anyone reaching for a distribution unit would write. A green run
        here is NOT evidence that a renamed container would be caught; it is
        evidence that Go compiles. The gate's KNOWN LIMITS says so at length,
        the measurement that makes a tighter needle unavailable is there (304
        code positions across 37 `package`-family words), and the two halves
        that can be closed are closed in internal/mapdef — decodeStrict's
        DisallowUnknownFields for the file format, which refuses `"package"`
        without knowing the name (TestAMapDeclaringAPackOrAPackageIsStillRefused
        drives it), and TestNoPackTypeOrLoaderRemainsInThisPackage's banned list
        for that package's declarations.
        """
        for spelling in ["package", "packages", "PACKAGES", "PACKAGE_CLAUSE_RE",
                         "packageManager", "go_package", "package_fingerprint",
                         "unresolvable_packages", "Subpackage", "packagePath",
                         "declared_package", "run_package", "packaged",
                         "packager"]:
            root = tree(**{"internal/a/a.go": "package a\n\nvar %s = 1\n" % spelling})
            try:
                code, _, err = run(root)
                self.assertEqual(code, 0, "%s: %s" % (spelling, err))
            finally:
                shutil.rmtree(root)

    def test_a_camel_boundary_after_the_stem_is_still_a_hit(self):
        """The hole a case-blind carve-out would open, and it is not theoretical.

        Lower-case the word first and `packAgent` becomes `packagent`, whose
        first four characters are followed by `age` — so a container helper
        called `packAgent`, `packAge` or `packAgency` would be filed under the
        English word and never reported. The needle keeps the case.
        """
        for spelling in ["packAgent", "PackAge", "packAgency"]:
            root = tree(**{"internal/a/a.go": "package a\n\nvar %s = 1\n" % spelling})
            try:
                code, _, err = run(root)
                self.assertEqual(code, 1, spelling)
                self.assertIn(spelling, err)
            finally:
                shutil.rmtree(root)

    def test_the_carve_out_is_case_aware_at_the_needle_itself(self):
        """The SECOND guard on the case-aware rule, and it is not decoration.

        test_a_camel_boundary_after_the_stem_is_still_a_hit drives the whole
        gate over a temp tree; against the SHIPPED exemption table it is the
        only test that fails when the carve-out is made case-blind, and one
        test standing between the tree and a silent hole is a coverage claim
        this repo does not accept. This one asserts the same rule one layer
        down, on the compiled pattern, so a regression has to defeat two
        mechanisms rather than one.
        """
        for word in ["package", "Package", "PACKAGE", "packages", "PACKAGES",
                     "Subpackage", "packagePath", "packaged", "packager"]:
            self.assertIsNone(gate.NEEDLE.search(word),
                              "%s is the English word and must not match" % word)
        for word in ["packAgent", "PackAge", "packAgency", "pack", "Pack",
                     "PACK", "packs", "LoadPack", "PACK_DIR"]:
            self.assertIsNotNone(gate.NEEDLE.search(word),
                                 "%s names the container and must match" % word)

    def test_a_camel_boundary_after_the_stem_is_caught_in_a_json_key_too(self):
        """The same rule through a different masker.

        The .json path keeps KEY text and blanks everything else, so a
        case-blind carve-out would hide a renamed container in a map file as
        readily as in Go — and no other test drives that combination.
        """
        root = tree(**{"campaigns/example/maps/m.json":
                       '{\n  "packAgent": "cellar-basics"\n}\n'})
        try:
            code, _, err = run(root)
            self.assertEqual(code, 1)
            self.assertIn("packAgent", err)
        finally:
            shutil.rmtree(root)

    def test_the_english_word_spelled_with_the_stem_is_a_stated_hole(self):
        """WRITTEN DOWN RATHER THAN HIDDEN, and asserted so it cannot drift.

        Every one of these is the container wearing the English word, and every
        one is CLEAN here. That is the gate's largest limit; it is in KNOWN
        LIMITS with the measurement that makes a tighter needle unavailable.
        This test exists so the limit is a fact in the suite rather than a
        sentence in a docstring — if a future needle ever does catch these,
        this test fails and the limit gets deleted rather than left stale.

        The two halves that ARE closed live in internal/mapdef and are proved
        there, not here: the `"package"` key is refused by loadAs, and
        `Package{`, `ArtPackage`, `LoadPackage` and `PackageTile` are banned in
        that package's own declarations.
        """
        body = ("package mapdef\n\n"
                "type ArtPackage struct{}\n"
                "func LoadPackage(d string) (*ArtPackage, error) { return nil, nil }\n"
                "func handlePackageFile() {}\n")
        root = tree(**{"internal/mapdef/load.go": body,
                       "campaigns/example/maps/m.json":
                       '{"package": "cellar-basics"}\n'})
        try:
            code, out, err = run(root)
            self.assertEqual(code, 0, err)
            self.assertIn("clean", out)
        finally:
            shutil.rmtree(root)

    def test_a_json_key_spelled_with_escapes_is_a_stated_hole(self):
        """`"\\u0070ack"` is the key `pack` to every JSON parser, and WORD
        matches identifier runs over the raw characters, so it contributes
        `u0070ack` and is not reported. In KNOWN LIMITS; pinned here so the
        limit is a fact rather than a claim."""
        root = tree(**{"campaigns/example/maps/m.json":
                       '{"\\u0070ack": "cellar-basics"}\n',
                       "internal/a/a.go": "package a\n"})
        try:
            code, out, err = run(root)
            self.assertEqual(code, 0, err)
            self.assertIn("clean", out)
        finally:
            shutil.rmtree(root)

    def test_the_neighbouring_english_words_are_reported_on_purpose(self):
        """STATED, not discovered. `packet`, `packed` and `unpack` are NOT
        carved out: each is one keystroke from the container's own vocabulary
        (`unpackArt` is precisely how a loader comes back), and none occurs at
        a code position in this tree today — measured 2026-09-06. If one
        arrives, it goes in EXEMPT with a reason, which is a decision somebody
        makes in public rather than a silence.
        """
        for spelling in ["packet", "packed", "unpack", "packetSize"]:
            root = tree(**{"internal/a/a.go": "package a\n\nvar %s = 1\n" % spelling})
            try:
                code, _, err = run(root)
                self.assertEqual(code, 1, spelling)
            finally:
                shutil.rmtree(root)


