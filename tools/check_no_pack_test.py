class TheShippedTableDescribesThisTree(unittest.TestCase):
    """An exemption that no longer applies must rot LOUDLY.

    Every entry names a real file and a word that really occurs there at a code
    position. Rename `packish` or delete a refusal test and the entry stops
    describing anything — and a dead exemption is a hole that widens silently as
    the file around it changes. This is the same move
    check_mutation_test.py's test_every_gated_package_in_the_real_tree_is_
    resolvable makes: assert the table against the tree it governs.
    """

    def test_every_entry_names_words_rather_than_a_whole_file(self):
        for rel, (allowed, reason) in gate.EXEMPT.items():
            self.assertIsNotNone(
                allowed, "%s is exempt WHOLESALE; name the words instead" % rel)
            self.assertTrue(reason, "%s has no reason" % rel)

    def test_every_exempted_word_is_a_mention_it_would_otherwise_report(self):
        for rel, (allowed, _) in gate.EXEMPT.items():
            for word in allowed:
                self.assertTrue(
                    gate.NEEDLE.search(word),
                    "%s: %r is not something this gate would report" % (rel, word))

    def test_every_exempted_word_still_occurs_where_it_is_exempted(self):
        for rel, (allowed, _) in gate.EXEMPT.items():
            path = os.path.join(_ROOT, rel)
            self.assertTrue(os.path.exists(path), "%s no longer exists" % rel)
            kind = gate.SOURCE_SUFFIXES[os.path.splitext(rel)[1]]
            with open(path, encoding="utf-8") as fh:
                code = gate.mask(fh.read(), kind)
            found = {m.group(0) for m in gate.WORD.finditer(code)}
            for word in allowed:
                self.assertIn(
                    word, found,
                    "%s no longer names %r at a code position; delete the "
                    "exemption rather than leaving a hole" % (rel, word))


