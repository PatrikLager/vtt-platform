#!/usr/bin/env python3
"""Boundary tests for check-no-pack.py.

The gate's whole value is the line it draws between the removed CONTAINER and
three things that look exactly like it in a grep and must survive:

  1. Go's own `package` keyword and the English word — 820 `package` and 103
     `packages` among the 1857 occurrences in the files this gate reads,
     measured 2026-09-06 over the tree as the gate found it. A needle that
     matched them would red on line 1 of every .go file, which is a gate
     switched off before lunch.
  2. THE STANDARD BASELINE PACK, which keeps its name on purpose
     (client/src/view/pack-assets.ts's header says so in as many words): a
     first-party manifest generated by tools/genmappack, shipped in the client
     bundle, served unauthenticated from /std-pack/. It is not a container a map
     claims and it did not leave.
  3. The tests whose JOB is to prove the container is gone, which have to write
     the word down in order to assert its absence. NO PRODUCTION FILE is in this
     family: internal/mapdef/load.go was, for mapJSON.Pack, until the migration
     route was deleted on 2026-09-06 and strict decoding turned out to be the
     whole of the refusal.

So the second and third families are EXEMPT, by word, with reasons; the first is
a STRUCTURAL carve-out, because a 923-entry exemption table is not a table, it
is a switch in the off position. TheEnglishWordIsNotTheNeedle below is that
carve-out's boundary, and TheStandardBaselineIsNotTheContainer is the other
one. Both are the tests most likely to be destroyed by a later widening.

Run: python3 tools/check_no_pack_test.py
"""

import importlib.util
import io
import os
import pathlib
import shutil
import tempfile
import unittest
from contextlib import redirect_stderr, redirect_stdout

_HERE = os.path.dirname(os.path.abspath(__file__))
_ROOT = os.path.dirname(_HERE)

_spec = importlib.util.spec_from_file_location(
    "check_no_pack", os.path.join(_HERE, "check-no-pack.py"))
gate = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(gate)


def tree(**files):
    """A temp source tree; returns its path. Keys use __ for subdirectories."""
    d = tempfile.mkdtemp()
    for name, body in files.items():
        p = pathlib.Path(d) / name.replace("__", "/")
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(body, encoding="utf-8")
    return d


def run(root):
    out, err = io.StringIO(), io.StringIO()
    with redirect_stdout(out), redirect_stderr(err):
        code = gate.main(["check-no-pack.py", root])
    return code, out.getvalue(), err.getvalue()


